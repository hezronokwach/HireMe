-- Baseline: the schema as Hibernate ddl-auto created it before Flyway was added.
-- Existing databases are baselined at version 1 (spring.flyway.baseline-on-migrate), so this
-- script only runs on new, empty databases.

CREATE SCHEMA IF NOT EXISTS app_user;
CREATE SCHEMA IF NOT EXISTS app_equipment;
CREATE SCHEMA IF NOT EXISTS app_booking;

CREATE TABLE app_user.users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(255) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    phone_number  VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(255),
    created_at    TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT users_email_key UNIQUE (email),
    CONSTRAINT users_phone_number_key UNIQUE (phone_number),
    CONSTRAINT users_role_check CHECK (role IN ('CLIENT', 'OWNER', 'ADMIN'))
);

CREATE TABLE app_equipment.equipment (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id       BIGINT,
    name           VARCHAR(255),
    category       VARCHAR(255),
    description    VARCHAR(255),
    daily_rate_kes NUMERIC(38, 2),
    location       VARCHAR(255),
    status         VARCHAR(255),
    created_at     TIMESTAMP(6) WITH TIME ZONE,
    updated_at     TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT equipment_category_check CHECK (category IN ('HEAVY_MACHINERY', 'AGRICULTURAL', 'EVENT_SETUP')),
    CONSTRAINT equipment_status_check CHECK (status IN ('AVAILABLE', 'HIRED', 'UNDER_MAINTENANCE'))
);

CREATE TABLE app_booking.bookings (
    booking_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id   BIGINT,
    client_id      BIGINT,
    start_date     DATE,
    end_date       DATE,
    total_cost_kes NUMERIC(38, 2),
    status         VARCHAR(255),
    creation_date  TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT bookings_status_check CHECK (status IN ('PENDING', 'CONFIRMED', 'ACTIVE', 'COMPLETED', 'CANCELLED'))
);

-- Spring Modulith event publication registry (spring-modulith-starter-jpa)
CREATE TABLE event_publication (
    id                     UUID PRIMARY KEY,
    listener_id            VARCHAR(255) NOT NULL,
    event_type             VARCHAR(255) NOT NULL,
    serialized_event       VARCHAR(255) NOT NULL,
    publication_date       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    completion_date        TIMESTAMP(6) WITH TIME ZONE,
    status                 VARCHAR(255),
    completion_attempts    INTEGER NOT NULL,
    last_resubmission_date TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT event_publication_status_check CHECK (status IN ('PUBLISHED', 'PROCESSING', 'COMPLETED', 'FAILED', 'RESUBMITTED'))
);

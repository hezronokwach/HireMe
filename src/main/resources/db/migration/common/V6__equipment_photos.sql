-- Photos of a listing. They are stored in the database, not on disk: the API's host (Render) loses its disk
-- on every deploy, and keeping them next to the listing needs no extra service. The browser shrinks photos
-- before upload, and the API caps their size and number, so the table stays small.
CREATE TABLE app_equipment.equipment_photo (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id BIGINT       NOT NULL REFERENCES app_equipment.equipment (id) ON DELETE CASCADE,
    content_type VARCHAR(50)  NOT NULL,
    image_data   BYTEA        NOT NULL,
    size_bytes   INTEGER      NOT NULL,
    sort_order   INTEGER      NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX equipment_photo_equipment_idx ON app_equipment.equipment_photo (equipment_id, sort_order);
